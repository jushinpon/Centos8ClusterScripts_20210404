#!/usr/bin/perl
use strict;
use warnings;

print "\n============================\n";
print "Installing OpenFOAM 12 (GitHub) on MASTER with SYSTEM OpenMPI\n";
print "============================\n\n";

# -------- [0/13] Clean any OpenFOAM RPM repo files --------
print "[0/13] Cleaning OpenFOAM RPM repos (we build from source)...\n";
system("find /etc/yum.repos.d/ -type f -iname '*openfoam*.repo' -exec rm -f {} \\;");

# -------- [1/13] Install dependencies & core CLI --------
print "[1/13] Installing build dependencies and core CLI tools...\n";
system("dnf -y groupinstall 'Development Tools'") == 0 or die "dev tools failed\n";
system("dnf -y install gcc gcc-c++ gcc-gfortran") == 0 or die "gcc/g++/gfortran failed\n";
system("dnf -y install git cmake flex bison pkgconfig") == 0 or die "git/cmake/flex/bison/pkgconfig failed\n";
system("dnf -y install boost-devel gmp-devel mpfr-devel zlib-devel") == 0 or die "boost/gmp/mpfr/zlib failed\n";
system("dnf -y install python3 python3-devel python3-pip") == 0 or die "python failed\n";
system("dnf -y install qt5-qtbase-devel qt5-qttools-devel") == 0 or die "Qt5 failed\n";
system("dnf -y install openmpi openmpi-devel hwloc hwloc-devel numactl-libs") == 0 or die "OpenMPI stack failed\n";
system("dnf -y install scotch-devel metis metis-devel || true");
system("dnf -y install readline-devel ncurses-devel libXt-devel libXext-devel libXrender-devel") == 0 or die "X11 headers failed\n";
system("dnf -y install coreutils grep gawk findutils glibc-common which util-linux") == 0 or die "core CLI failed\n";
system("dnf -y install environment-modules wget curl") == 0 or die "misc tools failed\n";

# -------- [2/13] Paths, env, symlink fix for OpenMPI lib64 --------
print "[2/13] Preparing dirs/env and fixing OpenMPI lib path...\n";
my $foam_base      = "/opt/OpenFOAM";
my $foam_ver       = "12";
my $openfoam_dir   = "$foam_base/OpenFOAM-$foam_ver";
my $thirdparty_dir = "$foam_base/ThirdParty-$foam_ver";
system("mkdir -p $foam_base") == 0 or die "mkdir $foam_base failed\n";

# OpenMPI layout on Rocky 8
my $MPI_BIN = "/usr/lib64/openmpi/bin";
my $MPI_LIB = "/usr/lib64/openmpi/lib";
my $MPI_INC = "/usr/include/openmpi-x86_64";

# Some third-party builds (e.g. Zoltan) wrongly look in .../lib64 — provide a symlink
if (! -d "/usr/lib64/openmpi/lib64") {
  system("ln -s $MPI_LIB /usr/lib64/openmpi/lib64") == 0 or warn "could not create lib64 symlink, continuing\n";
}

# Export env via %ENV (avoids shell quoting gotchas)
$ENV{PATH} = "/usr/bin:$MPI_BIN:" . ($ENV{PATH} // "");
$ENV{LD_LIBRARY_PATH} = $MPI_LIB . ":" . ($ENV{LD_LIBRARY_PATH} // "");
$ENV{OMPI_CC}  = "/usr/bin/gcc";
$ENV{OMPI_CXX} = "/usr/bin/g++";

# Also export for 3rd-party configure steps
$ENV{CC}     = "mpicc";
$ENV{CXX}    = "mpicxx";
$ENV{MPICC}  = "mpicc";
$ENV{MPICXX} = "mpicxx";
$ENV{CPPFLAGS} = "-I$MPI_INC " . ($ENV{CPPFLAGS} // "");
$ENV{CFLAGS}   = "-I$MPI_INC " . ($ENV{CFLAGS} // "");
$ENV{CXXFLAGS} = "-I$MPI_INC " . ($ENV{CXXFLAGS} // "");
$ENV{LDFLAGS}  = "-L$MPI_LIB " . ($ENV{LDFLAGS} // "");

# Jobs for make
my $jobs = `nproc 2>/dev/null`; chomp $jobs; $jobs = ($jobs =~ /^\d+$/) ? $jobs : 4;

# -------- [3/13] Clone OpenFOAM-12 --------
print "[3/13] Cloning OpenFOAM-12 from GitHub...\n";
chdir($foam_base) or die "chdir $foam_base failed\n";
if (-d $openfoam_dir) {
  chdir($openfoam_dir) or die "chdir $openfoam_dir failed\n";
  system("git fetch --depth=1 origin") == 0 or die "git fetch (OF) failed\n";
  system("git reset --hard origin/master") == 0 or die "git reset (OF) failed\n";
} else {
  system("git clone --depth 1 https://github.com/OpenFOAM/OpenFOAM-12.git") == 0
    or die "git clone (OF) failed\n";
}

# -------- [4/13] Clone ThirdParty-12 --------
print "[4/13] Cloning ThirdParty-12 from GitHub...\n";
chdir($foam_base) or die "chdir $foam_base failed\n";
if (-d $thirdparty_dir) {
  chdir($thirdparty_dir) or die "chdir $thirdparty_dir failed\n";
  system("git fetch --depth=1 origin") == 0 or die "git fetch (TP) failed\n";
  system("git reset --hard origin/master") == 0 or die "git reset (TP) failed\n";
} else {
  system("git clone --depth 1 https://github.com/OpenFOAM/ThirdParty-12.git") == 0
    or die "git clone (TP) failed\n";
}

# -------- [5/13] prefs.sh to force SYSTEMOPENMPI & MPI dirs --------
print "[5/13] Writing $openfoam_dir/etc/prefs.sh ...\n";
my $prefs = "$openfoam_dir/etc/prefs.sh";
open(my $pfh, '>', $prefs) or die "write $prefs failed\n";
print $pfh "# Auto-generated by installer\n";
print $pfh "export WM_MPLIB=SYSTEMOPENMPI\n";
print $pfh "export MPI_HOME=/usr/lib64/openmpi\n";
print $pfh "export MPI_ARCH_PATH=\$MPI_HOME\n";
print $pfh "export MPI_BIN=$MPI_BIN\n";
print $pfh "export MPI_LIB_DIR=$MPI_LIB\n";
print $pfh "export MPI_INCLUDE_DIR=$MPI_INC\n";
print $pfh "export PATH=\$MPI_BIN:\$PATH\n";
print $pfh "export LD_LIBRARY_PATH=\$MPI_LIB_DIR:\$LD_LIBRARY_PATH\n";
print $pfh "export CC=mpicc\n";
print $pfh "export CXX=mpicxx\n";
print $pfh "export MPICC=mpicc\n";
print $pfh "export MPICXX=mpicxx\n";
print $pfh "export CPPFLAGS=\"-I$MPI_INC \$CPPFLAGS\"\n";
print $pfh "export CFLAGS=\"-I$MPI_INC \$CFLAGS\"\n";
print $pfh "export CXXFLAGS=\"-I$MPI_INC \$CXXFLAGS\"\n";
print $pfh "export LDFLAGS=\"-L$MPI_LIB \$LDFLAGS\"\n";
close($pfh);

# -------- [6/13] System-wide env file --------
print "[6/13] Writing /etc/profile.d/openfoam.sh ...\n";
open(my $efh, '>', '/etc/profile.d/openfoam.sh') or die "write /etc/profile.d/openfoam.sh failed\n";
print $efh "source $openfoam_dir/etc/bashrc\n";
close($efh);
chmod 0755, '/etc/profile.d/openfoam.sh';

# -------- [7/13] Verify MPI toolchain --------
print "[7/13] Verifying MPI toolchain (compile & run hello)...\n";
my $hello = "/tmp/mpi_hello.c";
open(my $hfh, '>', $hello) or die "write $hello failed\n";
print $hfh "#include <mpi.h>\n#include <stdio.h>\nint main(int argc,char**argv){MPI_Init(&argc,&argv);int r;MPI_Comm_rank(MPI_COMM_WORLD,&r);if(r==0)puts(\"MPI OK\");MPI_Finalize();return 0;}\n";
close($hfh);
system("mpicc $hello -I$MPI_INC -L$MPI_LIB -lmpi -o /tmp/mpi_hello") == 0 or die "mpicc link failed\n";
system("/tmp/mpi_hello") == 0 or die "MPI run failed\n";

# -------- [8/13] Sanity-check core CLI tools --------
print "[8/13] Verifying presence of core CLI tools...\n";
for my $tool (qw(head grep dirname awk getconf readlink basename id uname)) {
  my $rc = system("command -v $tool >/dev/null 2>&1");
  die "missing tool: $tool\n" if $rc != 0;
}

# -------- [9/13] Build OpenFOAM (tee to log) --------
print "[9/13] Building OpenFOAM 12 (jobs=$jobs)...\n";
my $bashrc = "$openfoam_dir/etc/bashrc";
my $build_log = "/root/openfoam_build.log";
my $build_cmd = "source $bashrc && $openfoam_dir/Allwmake -j $jobs 2>&1 | tee $build_log";
my $build_rc  = system("/bin/bash","-lc",$build_cmd);
if ($build_rc != 0) {
  print "❌ Build failed. See $build_log and makeLogs under $openfoam_dir/platforms/*/makeLogs/\n";
  die "build failed\n";
}

# -------- [10/13] Re-run third-party build if needed (optional) --------
# (Left out for simplicity; Allwmake handles staged builds)

# -------- [11/13] foamInstallationTest (tee to log) --------
print "[11/13] Running foamInstallationTest...\n";
my $test_log = "/root/foam_install_test.log";
my $test_cmd = "source $bashrc && foamInstallationTest 2>&1 | tee $test_log";
my $test_rc  = system("/bin/bash","-lc",$test_cmd);
if ($test_rc != 0) {
  print "⚠️ foamInstallationTest reported issues – see $test_log\n";
}

# -------- [12/13] Summary --------
print "[12/13] Build complete.\n";
print "  OpenFOAM   : $openfoam_dir\n";
print "  ThirdParty : $thirdparty_dir\n";
print "  Env file   : /etc/profile.d/openfoam.sh\n";
print "  MPI bin    : $MPI_BIN\n";
print "  MPI inc    : $MPI_INC\n";
print "  MPI lib    : $MPI_LIB\n";
print "  Build log  : $build_log\n";
print "  Test log   : $test_log\n";

# -------- [13/13] Stop here for verification --------
print "[13/13] Master installation finished. Verify, then proceed to nodes.\n";
print "  Test:\n";
print "    source $openfoam_dir/etc/bashrc\n";
print "    foamInstallationTest\n";
print "    which simpleFoam && simpleFoam -help | head -n 3\n";
print "    cat $build_log | tail -n 50\n";

die;  # stop after master install for verification
